-- FINAL SCHEMA OF THE TABLES/ VARIABLES USED IN THE PROJECT
-- 1. Users Table
CREATE TABLE IF NOT EXISTS public.users (
    id SERIAL PRIMARY KEY,
    email VARCHAR(255) UNIQUE NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 2. Hazards Table
CREATE TABLE IF NOT EXISTS public.hazards (
    id SERIAL PRIMARY KEY,
    reporter_user_id INTEGER NOT NULL REFERENCES public.users(id),
    category VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'Reported',
    latitude DOUBLE PRECISION NOT NULL CHECK (latitude BETWEEN -90 AND 90), 
    longitude DOUBLE PRECISION NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    location_name VARCHAR(255),
    image_url TEXT,
    severity SMALLINT,
    created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);

-- 3. Chat Messages Table
CREATE TABLE IF NOT EXISTS public.chat_message (
    message_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id INTEGER REFERENCES public.users(id),
    hazard_id INTEGER REFERENCES public.hazards(id) ON DELETE CASCADE,
    message TEXT,
    vote INTEGER DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW() NOT NULL
);

-- 4. Voted Table 
CREATE TABLE IF NOT EXISTS public.voted (
    message_id INTEGER REFERENCES public.chat_message(message_id) ON DELETE CASCADE,
    user_id INTEGER REFERENCES public.users(id) ON DELETE CASCADE,
    PRIMARY KEY (message_id, user_id)
);

-- 5. Notifications Table
CREATE TABLE IF NOT EXISTS public.notifications (
    id SERIAL PRIMARY KEY,
    user_id INTEGER NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    hazard_id INTEGER REFERENCES public.hazards(id) ON DELETE CASCADE,
    message TEXT NOT NULL,
    type VARCHAR(50),
    is_read BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. Status Updates Table
CREATE TABLE IF NOT EXISTS public.status_updates (
    id SERIAL PRIMARY KEY,
    hazard_id INTEGER NOT NULL REFERENCES public.hazards(id) ON DELETE CASCADE,
    staff_user_id INTEGER NOT NULL REFERENCES public.users(id),
    old_status VARCHAR(50) NOT NULL,
    new_status VARCHAR(50) NOT NULL,
    note TEXT,
    updated_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP NOT NULL
);